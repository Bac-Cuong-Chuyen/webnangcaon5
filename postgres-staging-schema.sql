
    create table audit_log (
        created_at timestamp(6),
        id bigint generated by default as identity,
        action varchar(255),
        entity_name varchar(255),
        username varchar(255),
        primary key (id)
    );

    create table category (
        id bigint generated by default as identity,
        description varchar(255),
        name varchar(255),
        primary key (id)
    );

    create table customer (
        id bigint generated by default as identity,
        code varchar(255),
        email varchar(255),
        name varchar(255),
        phone varchar(255),
        primary key (id)
    );

    create table export_detail (
        quantity integer,
        id bigint generated by default as identity,
        product_id bigint,
        receipt_id bigint,
        primary key (id)
    );

    create table export_receipt (
        receipt_date date,
        id bigint generated by default as identity,
        warehouse_id bigint,
        approved_by varchar(255),
        created_by varchar(255),
        receipt_code varchar(255),
        status varchar(255),
        primary key (id)
    );

    create table import_detail (
        quantity integer,
        id bigint generated by default as identity,
        product_id bigint,
        receipt_id bigint,
        primary key (id)
    );

    create table import_receipt (
        receipt_date date,
        id bigint generated by default as identity,
        warehouse_id bigint,
        approved_by varchar(255),
        created_by varchar(255),
        receipt_code varchar(255),
        status varchar(255),
        primary key (id)
    );

    create table inventory (
        minimum_quantity integer,
        quantity integer,
        id bigint generated by default as identity,
        product_id bigint,
        warehouse_id bigint,
        primary key (id)
    );

    create table product (
        price numeric(38,2),
        id bigint generated by default as identity,
        name varchar(255),
        sku varchar(255),
        unit varchar(255),
        primary key (id)
    );

    create table stock_transfer (
        transfer_date date,
        from_warehouse_id bigint,
        id bigint generated by default as identity,
        to_warehouse_id bigint,
        approved_by varchar(255),
        created_by varchar(255),
        status varchar(255),
        transfer_code varchar(255),
        primary key (id)
    );

    create table suppliers (
        id bigint generated by default as identity,
        name varchar(255),
        primary key (id)
    );

    create table transfer_detail (
        quantity integer,
        id bigint generated by default as identity,
        product_id bigint,
        transfer_id bigint,
        primary key (id)
    );

    create table user_account (
        id bigint generated by default as identity,
        password varchar(255),
        role varchar(255) check (role in ('ADMIN','WAREHOUSE_MANAGER','WAREHOUSE_STAFF','DIRECTOR')),
        username varchar(255),
        primary key (id)
    );

    create table warehouse (
        id bigint generated by default as identity,
        address varchar(255),
        code varchar(255),
        name varchar(255),
        primary key (id)
    );
